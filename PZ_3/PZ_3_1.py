# Дано целое число А.
# Проверить истинность высказывания: "Число А является четным"
a = input("Введите четное число")
while type(a) != int:
    try:
        a = int(a)
    except ValueError:
        print("Неправильно ввели!")
        a = input("Введите число")
if a % 2 == 0:
     print("Число А", a, "является четным")
else:
     print("Число А", a, "является нечетным")
